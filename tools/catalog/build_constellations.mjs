import { readFileSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';

const source = 'https://github.com/Stellarium/stellarium/blob/daace2add6a1bf886e8ee1934f51e9c69f818d18/skycultures/modern/index.json';
const { constellations, common_names: commonNames } = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const { common_names: chineseNames } = JSON.parse(readFileSync(process.argv[3], 'utf8'));
const catalog = JSON.parse(readFileSync(new URL('catalog.json', import.meta.url), 'utf8'));
const catalogById = new Map(catalog.map((entry) => [entry.id, entry]));
const greek = new Map(Object.entries({
  Alp: 'α', Bet: 'β', Gam: 'γ', Del: 'δ', Eps: 'ε', Zet: 'ζ', Eta: 'η', The: 'θ',
  Iot: 'ι', Kap: 'κ', Lam: 'λ', Mu: 'μ', Nu: 'ν', Xi: 'ξ', Omi: 'ο', Pi: 'π',
  Rho: 'ρ', Sig: 'σ', Tau: 'τ', Ups: 'υ', Phi: 'φ', Chi: 'χ', Psi: 'ψ', Ome: 'ω'
}));
const paths = constellations.flatMap(({ lines }) => lines);
const hips = [...new Set(paths.flat())].sort((a, b) => a - b);
const wanted = new Set(hips);
const coordinates = new Map();
const hyg = gunzipSync(readFileSync(new URL('source/hyg_v35.csv.gz', import.meta.url))).toString('utf8');
for (const line of hyg.split(/\r?\n/)) {
  const hip = Number(line.split(',', 2)[1]);
  if (!wanted.has(hip)) continue;
  const fields = [...line.matchAll(/(?:^|,)("(?:[^"]|"")*"|[^,]*)/g)]
    .map((match) => match[1].replace(/^"|"$/g, '').replace(/""/g, '"').trim());
  const ra = Number(fields[7]);
  const dec = Number(fields[8]);
  if (fields[7] && fields[8] && ra >= 0 && ra < 24 && dec >= -90 && dec <= 90) {
    coordinates.set(hip, fields);
  }
}

const missing = hips.filter((hip) => !coordinates.has(hip));
if (constellations.length !== 88 || missing.length > 0) {
  throw new Error(`Expected 88 complete figures. Found ${constellations.length}, missing HIP ${missing.join(', ')}.`);
}
const indexes = new Map(hips.map((hip, index) => [hip, index]));
const edges = new Set();
for (const path of paths) {
  for (let i = 1; i < path.length; i++) {
    const first = indexes.get(path[i - 1]);
    const second = indexes.get(path[i]);
    if (first !== second) edges.add(`[${Math.min(first, second)}, ${Math.max(first, second)}]`);
  }
}
const stars = hips.map((hip) => {
  const fields = coordinates.get(hip);
  const id = `HIP${hip}`;
  const prior = catalogById.get(id);
  const otherNames = (commonNames?.[`HIP ${hip}`] ?? []).map((n) => n.english || n.native).filter(Boolean);
  const bayer = fields[27].replace(/^[A-Za-z]+/, (letters) => greek.get(letters) ?? letters);
  const designation = fields[29] && bayer ? `${bayer} ${fields[29]}` : '';
  const flamsteed = fields[29] && fields[28] ? `${fields[28]} ${fields[29]}` : '';
  const hr = fields[3] ? `HR${fields[3]}` : '';
  const nameEn = fields[6] || otherNames[0] || designation || flamsteed || hr || id;
  const nativeNames = (chineseNames[`HIP ${hip}`] ?? []).map((entry) => entry.native)
    .filter((native) => native && /\p{Script=Han}/u.test(native) && !native.includes('?'));
  const catalogName = prior?.name;
  const familiarChineseName = catalogName && /\p{Script=Han}/u.test(catalogName) &&
    !/座(?:\p{Script=Greek}|\d+星)/u.test(catalogName) ? catalogName : '';
  const name = familiarChineseName || nativeNames[0] || (catalogName !== id ? catalogName : '') || nameEn;
  const aliases = [...new Set([
    designation, flamsteed, fields[5], hr, catalogName, prior?.nameEn, ...otherNames, ...nativeNames, `HIP ${hip}`
  ].filter(Boolean))];
  const distancePc = Number(fields[9]);
  const distanceLy = distancePc > 0 && distancePc < 10000 ? Number((distancePc * 3.26156).toFixed(1)) : 0;
  const mag = fields[13] ? Number(fields[13]) : 99;
  const record = { id, name, nameEn, aliases, raHours: Number(fields[7]), decDeg: Number(fields[8]), mag, distanceLy };
  return `  ${JSON.stringify(record)},`;
});
const edgeRows = [...edges].map((edge) => `  ${edge},`);
const out = new URL('../../starpilot-watch/entry/src/main/ets/data/Constellations.ets', import.meta.url);
writeFileSync(out, [
  '// Generated by tools/catalog/build_constellations.mjs.',
  '// Stick figures adapted from Stellarium Modern by the Stellarium team.',
  `// ${source}`,
  '// Anchor coordinates and designations from Astronexus HYG v3.5, with Stellarium Modern name aliases.',
  '// Traditional Chinese names from Stellarium Chinese sky culture v26.3.',
  '// Data licensed CC BY-SA 4.0. https://creativecommons.org/licenses/by-sa/4.0/',
  "import { Equatorial } from '../common/Astro';",
  '',
  'export interface ConstellationStar extends Equatorial {',
  '  id: string;',
  '  name: string;',
  '  nameEn: string;',
  '  aliases: string[];',
  '  mag: number;',
  '  distanceLy: number;',
  '}',
  '',
  'export const CONSTELLATION_STARS: ConstellationStar[] = [',
  ...stars,
  '];',
  '',
  'export const CONSTELLATION_EDGES: number[][] = [',
  ...edgeRows,
  '];',
  ''
].join('\n'));
console.log(`${constellations.length} figures, ${hips.length} stars, ${edges.size} edges`);
