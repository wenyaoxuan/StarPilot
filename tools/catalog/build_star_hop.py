"""Build from local HYG v3.5 and the Stellarium Chinese v26.3 index.json."""
import csv
import gzip
import json
import re
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
DATA = TOOLS.parent.parent / 'starpilot-watch/entry/src/main/ets/data'
anchors = [json.loads(row) for row in re.findall(
    r'^  (\{.*\}),?$', (DATA / 'Constellations.ets').read_text(encoding='utf-8'), re.M)]
targets = json.loads((TOOLS / 'catalog.json').read_text(encoding='utf-8'))
chinese = json.loads(Path(sys.argv[1]).read_text(encoding='utf-8'))['common_names']
existing = {row['id'] for row in anchors + targets}
constellations = {}
supplement = {}
with gzip.open(TOOLS / 'source/hyg_v35.csv.gz', 'rt', encoding='utf-8') as source:
    for row in csv.DictReader(source):
        if not row['hip'] or not row['con'] or row['proper'] == 'Sol':
            continue
        hip = int(row['hip'])
        key = f'HIP{hip}'
        if key in existing:
            constellations[hip] = row['con']
            continue
        mag = float(row['mag'])
        if mag > 4:
            continue
        if hip in supplement and supplement[hip]['mag'] <= mag:
            continue
        designation = ' '.join(row['bf'].split())
        english = row['proper'] or designation or f'HIP {hip}'
        name = next((entry['native'] for entry in chinese.get(f'HIP {hip}', [])
                     if re.search(r'[\u3400-\u9fff]', entry.get('native', '')) and '?' not in entry['native']),
                    english)
        supplement[hip] = dict(id=key, name=name, nameEn=english, constellation=row['con'],
                               raHours=float(row['ra']), decDeg=float(row['dec']), mag=mag,
                               identifiable=bool(row['proper'] or row['bayer']))

chunks = [f'{hip}:{con}' for hip, con in sorted(constellations.items())]
encoded = [','.join(chunks[i:i + 12]) for i in range(0, len(chunks), 12)]
lines = [
    '// Generated by tools/catalog/build_star_hop.py.',
    '// HYG v3.5 (Astronexus), J2000. Adapted data CC BY-SA 4.0.',
    '// Chinese names matched by HIP from Stellarium Chinese v26.3.',
    "import { HopStar } from '../common/StarHopEngine';",
    '',
    'export const EXTRA_HOP_STARS: HopStar[] = [',
    *(f'  {json.dumps(row, ensure_ascii=False, separators=(",", ":"))},'
      for _, row in sorted(supplement.items())),
    '];',
    '',
    'export const HOP_CONSTELLATIONS: string =',
    ' +\n'.join(f"  '{chunk}{',' if i < len(encoded) - 1 else ''}'"
                 for i, chunk in enumerate(encoded)) + ';',
]
(DATA / 'StarHopSupplement.ets').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'{len(supplement)} additional stars, '
      f'{sum(r["name"] != r["nameEn"] for r in supplement.values())} Chinese names, '
      f'{len(constellations)} existing HIP constellation tags')
